from datetime import datetime

from pydantic import BaseModel, ConfigDict, Field

from app.models.project_members import ProjectRole


class ProjectCreate(BaseModel):
    """Payload for creating a project.

    The ``slug`` is generated by the backend from the project name and is
    therefore never accepted from the client.
    """

    name: str = Field(min_length=1, max_length=255)
    description: str | None = None


class ProjectUpdate(BaseModel):
    """Editable project fields. ``slug`` is intentionally immutable so the
    widget report URL stays stable."""

    name: str | None = Field(default=None, min_length=1, max_length=255)
    description: str | None = None
    is_archived: bool | None = None


class ProjectOut(BaseModel):
    model_config = ConfigDict(from_attributes=True)

    id: int
    name: str
    slug: str
    description: str | None
    is_archived: bool
    owner_id: int
    created_at: datetime
    updated_at: datetime


class ProjectMemberCreate(BaseModel):
    email: str
    role: ProjectRole = ProjectRole.CONTRIBUTOR


class ProjectMemberUpdate(BaseModel):
    role: ProjectRole


class ProjectMemberUser(BaseModel):
    model_config = ConfigDict(from_attributes=True)

    id: int
    email: str
    full_name: str | None


class ProjectMemberOut(BaseModel):
    model_config = ConfigDict(from_attributes=True)

    id: int
    project_id: int
    user_id: int
    role: ProjectRole
    created_at: datetime
    user: ProjectMemberUser